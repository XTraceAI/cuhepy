"""E29: transpose the affine CRT index into the final response coordinates.

Each encrypted column serves every plaintext CRT component. A public correction
is constant inside each component, hence lies in the subring generated by
X**min_leaf_degree. The encryption ring and secret still have full degree N.
This is standard CRT/linear algebra used as a search representation experiment,
not a new encryption primitive. Map identifiers and geometry are public; the
affine maps themselves are never inputs to this module.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
import hashlib
import json

from experiments.bfv_search_lab import dyadic_crt as crt


@dataclass(frozen=True)
class Space:
    layout: crt.Layout
    map_ids: tuple[int, ...]
    dimensions: tuple[int, ...]
    shared: int = 0  # E30: a common prefix of private query forms, masked once.

    @property
    def dimension(self) -> int:
        return self.shared + sum(f - self.shared for f in self.dimensions)

    @property
    def columns(self) -> int:
        return max(self.dimensions)

    @property
    def stride(self) -> int:
        return min(leaf.degree for leaf in self.layout.context.leaves)

    @property
    def slots(self) -> int:
        return self.layout.context.n // self.stride

    @property
    def column_degrees(self) -> tuple[int, ...]:
        return (1,) * self.shared + (self.slots,) * (self.columns - self.shared)

    @property
    def binding(self) -> bytes:
        body = asdict(self)
        if not self.shared:
            del body["shared"]  # Preserve existing E29 epoch/mask bindings.
        return hashlib.sha256(json.dumps(body, sort_keys=True, separators=(",", ":")).encode()).digest()


def space(layout: crt.Layout, map_ids: tuple[int, ...], *, shared: int = 0) -> Space:
    crt.validate_layout(layout)
    if (type(map_ids) is not tuple or len(map_ids) != len(layout.features)
            or any(type(i) is not int or i < 0 for i in map_ids)
            or tuple(dict.fromkeys(map_ids)) != tuple(range(len(set(map_ids))))):
        raise ValueError("Expected canonical public component-to-map identifiers")
    dimensions = []
    for i in range(len(set(map_ids))):
        sizes = {f for f, group in zip(layout.features, map_ids, strict=True) if group == i}
        if len(sizes) != 1:
            raise ValueError("Replicated maps must have the same public feature count")
        dimensions.append(sizes.pop())
    if type(shared) is not int or not 0 <= shared <= min(dimensions):
        raise ValueError("Invalid common query prefix")
    return Space(layout, map_ids, tuple(dimensions), shared)


def validate(s: Space) -> None:
    if s != space(s.layout, s.map_ids, shared=s.shared):
        raise ValueError("Inconsistent public CRT query space")


def split(s: Space, values: tuple[int, ...]) -> tuple[tuple[int, ...], ...]:
    validate(s)
    if len(values) != s.dimension or any(type(x) is not int for x in values):
        raise ValueError("Incorrect public query-space coordinates")
    result, start = [], s.shared
    for dimension in s.dimensions:
        width = dimension - s.shared
        result.append(values[:s.shared] + values[start:start + width])
        start += width
    return tuple(result)


def query(s: Space, values: tuple[int, ...]) -> list[int]:
    """The exact E27 query embedding, with shared weights for replicated maps."""
    groups = split(s, values)
    return crt.query(s.layout, [list(groups[i]) for i in s.map_ids])


def corrections(s: Space, values: tuple[int, ...]) -> tuple[tuple[int, ...], ...]:
    """Centered lifts of component constants, in the short Y=X**stride ring.

    Reduction modulo t is intentional and NOT linear over the ciphertext field.
    Verification must use these actual lifts, including their field wraparound.
    """
    groups = split(s, values)
    ctx = s.layout.context
    stride, p = s.stride, ctx.prime
    result: list[tuple[int, ...]] = []
    for j in range(s.columns):
        if j < s.shared:
            x = groups[0][j] % p
            result.append((x if x <= p // 2 else x - p,))
            continue
        # Interpolate directly in Y=X**stride, not N mostly-zero coefficients.
        work = {leaf.path: [groups[i][j] % p if j < len(groups[i]) else 0] + [0] * (leaf.degree // stride - 1)
                for i, leaf in zip(s.map_ids, ctx.leaves, strict=True)}
        for node in reversed(ctx.splits):
            left, right = work.pop(node.path + "0"), work.pop(node.path + "1")
            inverse, gamma_inverse = pow(2, -1, p), pow(2 * node.gamma, -1, p)
            work[node.path] = ([(a + b) * inverse % p for a, b in zip(left, right, strict=True)]
                               + [(a - b) * gamma_inverse % p for a, b in zip(left, right, strict=True)])
        result.append(tuple(x if x <= p // 2 else x - p for x in work[""]))
    return tuple(result)


def expand(s: Space, short: tuple[int, ...]) -> list[int]:
    if len(short) not in s.column_degrees or any(type(x) is not int for x in short):
        raise ValueError("Incorrect subring coefficient vector")
    result = [0] * s.layout.context.n
    result[::s.layout.context.n // len(short)] = short
    return result


def outputs(plan: crt.Layout, values: list[list[int]]) -> list[list[int]]:
    """Put scores in the exact coefficient locations consumed by E27 unpack()."""
    crt.validate_layout(plan)
    if (len(values) != len(plan.counts)
            or any(len(row) != count or any(type(x) is not int for x in row)
                   for row, count in zip(values, plan.counts, strict=True))):
        raise ValueError("Invalid component score vectors")
    components = [[[0] * leaf.degree for leaf in plan.context.leaves]
                  for _ in range(plan.cost.response_ciphertexts)]
    for component, (row, leaf) in enumerate(zip(values, plan.context.leaves, strict=True)):
        capacity = leaf.degree // plan.padded
        for i, value in enumerate(row):
            reply, within = divmod(i, leaf.degree)
            tile, lane = divmod(within, capacity)
            components[reply][component][lane * plan.padded + tile] = plan.padded * value
    return [crt.encode(plan.context, rows) for rows in components]


def validate_rows(s: Space, groups: list[list[list[int]]]) -> None:
    validate(s)
    if (len(groups) != len(s.layout.counts)
            or any(len(rows) != count or any(len(row) != f or any(type(x) is not int for x in row) for row in rows)
                   for rows, count, f in zip(groups, s.layout.counts, s.layout.features, strict=True))):
        raise ValueError("Invalid transposed enrollment rows")


def columns(s: Space, groups: list[list[list[int]]]) -> tuple[tuple[list[int], ...], ...]:
    """Owner-only plaintext transposition: F columns, not sum(map ranks)."""
    validate_rows(s, groups)
    return tuple(tuple(outputs(s.layout, [[row[j] if j < len(row) else 0 for row in rows] for rows in groups]))
                 for j in range(s.columns))


def scores(s: Space, groups: list[list[list[int]]], values: tuple[int, ...]) -> list[list[int]]:
    validate_rows(s, groups)
    weights = split(s, values)
    return [[sum(a * b for a, b in zip(row, weights[i], strict=True)) % s.layout.context.prime for row in rows]
            for rows, i in zip(groups, s.map_ids, strict=True)]


def cost(s: Space, *, q_bits: int = 40, eta: int = 21, rounds: int = 4) -> dict[str, int]:
    """Coefficient/body counts, not wire envelopes, security levels or timings."""
    validate(s)
    if (type(q_bits) is not int or not 32 <= q_bits <= 120 or type(eta) is not int or not 1 <= eta <= 64
            or type(rounds) is not int or not 1 <= rounds <= 8):
        raise ValueError("Invalid bounded cost profile")
    n, t, replies = s.layout.context.n, s.layout.context.prime, s.layout.cost.response_ciphertexts
    width, fresh = (q_bits + 7) // 8, t // 2 + t * eta  # Seeded symmetric owner encryption.
    body = replies * 2 * n * width
    coefficients = sum(s.column_degrees)
    scalar_columns = s.column_degrees.count(1)
    ring_columns = s.columns - scalar_columns
    return {"n": n, "t": t, "q_bits": q_bits, "query_coordinates": s.dimension,
            "coordinate_columns": s.columns, "subring_degree": s.slots, "replies": replies,
            "shared_query_coordinates": s.shared, "correction_coefficients": coefficients,
            "online_query_body_bytes": s.dimension * ((t.bit_length() + 7) // 8),
            "online_response_body_bytes": body, "expanded_index_body_bytes": s.columns * body,
            "naive_scalar_basis_index_body_bytes": s.dimension * body,
            "offline_seeded_answer_body_bytes_per_token": replies * ((n * q_bits + 7) // 8 + 32),
            "stored_expanded_answer_bytes_per_token": body, "owner_private_mask_seed_bytes_per_token": 32,
            "online_ring_products": 2 * replies * ring_columns,
            "online_scalar_products": 2 * replies * scalar_columns * n,
            "native_ntt_index_word_bytes": s.columns * replies * 2 * n * 8,
            "native_online_pointwise_scalar_products": 2 * replies * s.columns * n,
            "online_ciphertext_products": 0, "online_key_switches": 0,
            "worst_case_phase_bound": fresh * (1 + coefficients * (t // 2)),
            "fresh_phase_bound": fresh, "checker_rounds": rounds,
            "checker_prepare_ring_products": rounds * 2 * replies * ring_columns,
            "checker_prepare_scalar_products": rounds * 2 * replies * scalar_columns * n,
            "checker_epoch_residue_body_bytes": rounds * (2 * replies * n + coefficients) * width,
            "checker_epoch_seeded_body_bytes": rounds * (32 + coefficients * width),
            "checker_token_residue_body_bytes": rounds * width,
            "checker_online_scalar_products": rounds * (2 * replies * n + coefficients),
            "full_degree_single_encryption_ciphertext_body_bytes": 2 * n * width}
